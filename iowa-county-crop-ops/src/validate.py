import sqlite3

import numpy as np
import pandas as pd

DB = "data/iowa_crops.db"
OUT = "docs/validation.md"


def coverage(con):
    sql = """
    SELECT k.commodity, f.year,
           COUNT(*) AS counties_published,
           SUM(f.production_bu) AS county_sum_bu,
           s.production_bu AS state_bu,
           ROUND(100.0 * SUM(f.production_bu) / s.production_bu, 1) AS pct_of_state
    FROM fact_crop_county_year f
    JOIN dim_crop k USING (crop_id)
    JOIN fact_crop_state_year s ON s.crop_id = f.crop_id AND s.year = f.year
    WHERE f.year <= 2025
    GROUP BY k.commodity, f.year, s.production_bu
    ORDER BY k.commodity, f.year
    """
    return pd.read_sql_query(sql, con)


def sanity(con):
    checks = []
    bad_ratio = con.execute("SELECT COUNT(*) FROM fact_crop_county_year WHERE acres_harvested > acres_planted").fetchone()[0]
    checks.append(("county-years with harvested acres above planted acres", bad_ratio))
    bad_prod = con.execute("""SELECT COUNT(*) FROM fact_crop_county_year
                              WHERE ABS(production_bu - acres_harvested * yield_bu_acre) > 0.02 * production_bu""").fetchone()[0]
    checks.append(("county-years where production differs from harvested acres times yield by over 2 percent", bad_prod))
    corn = con.execute("SELECT MIN(yield_bu_acre), MAX(yield_bu_acre) FROM fact_crop_county_year WHERE crop_id = 1").fetchone()
    soy = con.execute("SELECT MIN(yield_bu_acre), MAX(yield_bu_acre) FROM fact_crop_county_year WHERE crop_id = 2").fetchone()
    checks.append(("corn yield range, bushels per acre", f"{corn[0]:.1f} to {corn[1]:.1f}"))
    checks.append(("soybean yield range, bushels per acre", f"{soy[0]:.1f} to {soy[1]:.1f}"))
    seasons = con.execute("SELECT COUNT(*), MIN(season_days), MAX(season_days) FROM fact_weather_district_season").fetchone()
    checks.append(("district seasons loaded, with min and max days per season", f"{seasons[0]}, {seasons[1]} to {seasons[2]}"))
    lookup = pd.read_csv("data/lookups/county_to_district.csv")
    checks.append(("counties whose NASS district and NCEI climate division disagree", int((~lookup.same_boundary).sum())))
    return checks


def trend_check(con):
    rows = pd.read_sql_query("""
        SELECT c.county_name, k.commodity, f.year, f.yield_bu_acre
        FROM fact_crop_county_year f JOIN dim_county c USING (county_fips) JOIN dim_crop k USING (crop_id)
        WHERE c.county_name IN ('POLK', 'STORY', 'APPANOOSE') AND f.yield_bu_acre IS NOT NULL""", con)
    sql_out = pd.read_csv("data/outputs/04_trend_residual_bad_years.csv")
    results = []
    for (county, crop), g in rows.groupby(["county_name", "commodity"]):
        slope, intercept = np.polyfit(g.year - 2000.0, g.yield_bu_acre, 1)
        trend_2012 = intercept + slope * 12
        got = sql_out[(sql_out.county_name == county) & (sql_out.commodity == crop) & (sql_out.year == 2012)].trend_yield.iloc[0]
        results.append((county, crop, round(trend_2012, 1), got, abs(trend_2012 - got) < 0.15))
    return results


def main():
    con = sqlite3.connect(DB)
    cov = coverage(con)
    checks = sanity(con)
    trend = trend_check(con)
    cov.to_csv("data/outputs/validation_coverage.csv", index=False)
    lines = ["# Validation", "", "Generated by `src/validate.py` from the loaded database.", "",
             "## County sums against the state total", "",
             "Published county production as a share of the NASS state figure for the same crop and year. The gap is the counties NASS folded into its combined-county rows, which this project drops.", "",
             "| Crop | Years at 99 counties | Lowest coverage (year) | Highest coverage (year) |", "|---|---|---|---|"]
    for crop, g in cov.groupby("commodity"):
        full = int((g.counties_published == 99).sum())
        lo = g.loc[g.pct_of_state.idxmin()]
        hi = g.loc[g.pct_of_state.idxmax()]
        lines.append(f"| {crop.title()} | {full} of {len(g)} | {lo.pct_of_state}% ({int(lo.year)}, {int(lo.counties_published)} counties) | {hi.pct_of_state}% ({int(hi.year)}) |")
    lines += ["", "Full table: `data/outputs/validation_coverage.csv`.", "", "## Row checks", "", "| Check | Result |", "|---|---|"]
    for name, value in checks:
        lines.append(f"| {name} | {value} |")
    lines += ["", "## SQL trend fit against NumPy", "",
              "The straight-line trend in `sql/analysis/04_trend_residual_bad_years.sql` is fit with sums in SQL. The same fit with `numpy.polyfit`, trend yield for 2012:", "",
              "| County | Crop | NumPy | SQL | Match |", "|---|---|---|---|---|"]
    for county, crop, np_val, sql_val, ok in trend:
        lines.append(f"| {county.title()} | {crop.title()} | {np_val} | {sql_val} | {'yes' if ok else 'no'} |")
    open(OUT, "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))
    con.close()


if __name__ == "__main__":
    main()
